"use client";

import { useState } from "react";
import DashboardShell from "@/components/DashboardShell";
import { getAlerts, markAlertRead } from "@/lib/api";
import usePolling from "@/lib/usePolling";

export default function AlertsPage() {
  const { data, error, loading, refresh } = usePolling((signal) => getAlerts(signal));
  const [updating, setUpdating] = useState<string | null>(null);
  const [actionError, setActionError] = useState("");

  const markRead = async (alertId: string) => {
    setUpdating(alertId);
    setActionError("");
    try {
      await markAlertRead(alertId);
      await refresh();
    } catch (caught) {
      setActionError(caught instanceof Error ? caught.message : "Could not update alert.");
    } finally {
      setUpdating(null);
    }
  };

  return (
    <DashboardShell>
      <main className="content">
        <header className="page-head">
          <div className="eyebrow">RISK NOTIFICATIONS</div>
          <h1>Alerts</h1>
          <p>Review risk notifications generated by your monitored sites.</p>
        </header>
        <section className="panel data-panel" aria-label="Risk alerts">
          <div className="data-toolbar">
            <span className="data-toolbar-title">Recent alerts</span>
            <button className="data-refresh" type="button" onClick={() => void refresh()}>Refresh</button>
          </div>
          {error && data && <p className="data-warning" role="status">Connection lost. Showing last updated data.</p>}
          {actionError && <p className="data-warning" role="alert">{actionError}</p>}
          {loading && !data ? (
            <div className="data-state" aria-live="polite">Loading alerts…</div>
          ) : error && !data ? (
            <div className="data-state data-error" role="alert">Could not load alerts. Use Refresh to try again.</div>
          ) : !data?.alerts.length ? (
            <div className="data-state">No alerts yet.</div>
          ) : (
            <ul className="alert-list">
              {data.alerts.map((alert) => (
                <li className={`alert-item${alert.read ? "" : " unread"}`} key={alert.id}>
                  <div className="alert-copy">
                    <p className="alert-message">{alert.message}</p>
                    <p className="alert-meta">
                      {alert.site_url} · {alert.pattern_type.replaceAll("_", " ")} · {new Date(`${alert.created_at}${/[zZ]|[+-]\d{2}:\d{2}$/.test(alert.created_at) ? "" : "Z"}`).toLocaleString()}
                    </p>
                  </div>
                  {!alert.read && (
                    <button
                      className="data-refresh"
                      type="button"
                      disabled={updating === alert.id}
                      onClick={() => void markRead(alert.id)}
                    >
                      {updating === alert.id ? "Updating…" : "Mark read"}
                    </button>
                  )}
                  {alert.read && <span className="alert-read-label">Read</span>}
                </li>
              ))}
            </ul>
          )}
        </section>
      </main>
    </DashboardShell>
  );
}
